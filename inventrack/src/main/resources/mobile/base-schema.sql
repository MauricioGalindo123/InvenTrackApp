CREATE TABLE Categorias
(
  IDcategorias INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  Nombre       VARCHAR(200) NOT NULL,
  Descripcion  VARCHAR(100) NULL,
  PRIMARY KEY (IDcategorias)
);

CREATE TABLE Marcas
(
  IDmarca     INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  Nombre      VARCHAR(100) NOT NULL,
  Descripcion VARCHAR(200) NULL,
  Activo      BOOL         NOT NULL,
  PRIMARY KEY (IDmarca)
);

CREATE TABLE Sucursales
(
  IDSucursal INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  Nombre     VARCHAR(100) NOT NULL,
  Direccion  VARCHAR(200) NULL,
  Telefono   VARCHAR(50)  NULL,
  Activo     BOOL         NOT NULL,
  PRIMARY KEY (IDSucursal)
);

CREATE TABLE Usuario
(
  IDusuario     INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDSucursal    INT          NOT NULL,
  Nombre        VARCHAR(200) NOT NULL,
  Correo        VARCHAR(100) NOT NULL,
  Contrasena    VARCHAR(200) NOT NULL,
  Rol           VARCHAR(20)  NOT NULL,
  Acceso        TIMESTAMP    NULL,
  Activo        BOOL         NOT NULL,
  FechaCreacion TIMESTAMP    NOT NULL,
  PRIMARY KEY (IDusuario)
);

CREATE TABLE Producto
(
  IDproducto    INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDcategorias  INT           NOT NULL,
  IDmarca       INT           NULL,
  Codigo        VARCHAR(50)   NOT NULL,
  Nombre        VARCHAR(300)  NOT NULL,
  Descripcion   VARCHAR(200)  NULL,
  PrecioVenta   DECIMAL(10,2) NOT NULL,
  PrecioCosto   DECIMAL(10,2) NULL,
  StockMinimo   INT           NOT NULL,
  Activo        BOOL          NOT NULL,
  FechaCreacion TIMESTAMP     NOT NULL,
  PRIMARY KEY (IDproducto)
);

CREATE TABLE Inventario
(
  IDinventario       INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDSucursal         INT          NOT NULL,
  IDproducto         INT          NOT NULL,
  CantidadDisponible INT          NOT NULL,
  Ubicacion          VARCHAR(100) NULL,
  Actualizacion      TIMESTAMP    NULL,
  PRIMARY KEY (IDinventario)
);

CREATE TABLE Proveedores
(
  IDproveedor INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  Nombre      VARCHAR(200) NOT NULL,
  RFC_NIT     VARCHAR(50)  NOT NULL,
  Telefono    VARCHAR(50)  NULL,
  Correo      VARCHAR(100) NULL,
  Direccion   VARCHAR(200) NULL,
  Activo      BOOL         NOT NULL,
  PRIMARY KEY (IDproveedor)
);

CREATE TABLE Producto_proveedor
(
  IDproductoProveedor INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDproducto          INT           NOT NULL,
  IDproveedor         INT           NOT NULL,
  CodigoProveedor     VARCHAR(100)  NULL,
  PrecioCompra        DECIMAL(10,2) NOT NULL,
  Activo              BOOL          NOT NULL,
  PRIMARY KEY (IDproductoProveedor)
);

CREATE TABLE Clientes
(
  IDcliente     INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  Nombre        VARCHAR(200) NOT NULL,
  Documento     VARCHAR(50)  NOT NULL,
  Telefono      VARCHAR(50)  NULL,
  Correo        VARCHAR(100) NULL,
  Direccion     VARCHAR(200) NULL,
  FechaRegistro TIMESTAMP    NOT NULL,
  PRIMARY KEY (IDcliente)
);

CREATE TABLE Metodos_pago
(
  IDmetodoPago INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  Nombre       VARCHAR(50)  NOT NULL,
  Descripcion  VARCHAR(150) NULL,
  Activo       BOOL         NOT NULL,
  PRIMARY KEY (IDmetodoPago)
);

CREATE TABLE Ordenes_compra
(
  IDcompra    INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDproveedor INT           NOT NULL,
  IDSucursal  INT           NOT NULL,
  IDusuario   INT           NOT NULL,
  FechaCompra TIMESTAMP     NOT NULL,
  Total       DECIMAL(12,2) NOT NULL,
  Estado      VARCHAR(20)   NOT NULL,
  Observacion VARCHAR(300)  NULL,
  PRIMARY KEY (IDcompra)
);

CREATE TABLE Detalle_compra
(
  IDdetalleCompra INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDcompra        INT           NOT NULL,
  IDproducto      INT           NOT NULL,
  Cantidad        INT           NOT NULL,
  PrecioUnitario  DECIMAL(10,2) NOT NULL,
  Subtotal        DECIMAL(12,2) NOT NULL,
  PRIMARY KEY (IDdetalleCompra)
);

CREATE TABLE Ventas
(
  IDventa      INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDcliente    INT           NOT NULL,
  IDSucursal   INT           NOT NULL,
  IDusuario    INT           NOT NULL,
  IDmetodoPago INT           NOT NULL,
  FechaVenta   TIMESTAMP     NOT NULL,
  Total        DECIMAL(12,2) NOT NULL,
  Estado       VARCHAR(20)   NOT NULL,
  Observacion  VARCHAR(300)  NULL,
  PRIMARY KEY (IDventa)
);

CREATE TABLE Detalle_ventas
(
  IDdetalleVenta INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDventa        INT           NOT NULL,
  IDproducto     INT           NOT NULL,
  Cantidad       INT           NOT NULL,
  PrecioUnitario DECIMAL(10,2) NOT NULL,
  Descuento      DECIMAL(12,2) NOT NULL,
  Subtotal       DECIMAL(12,2) NOT NULL,
  PRIMARY KEY (IDdetalleVenta)
);

CREATE TABLE Traslados
(
  IDtraslado        INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDSucursalOrigen  INT          NOT NULL,
  IDSucursalDestino INT          NOT NULL,
  IDusuario         INT          NOT NULL,
  FechaSolicitud    TIMESTAMP    NOT NULL,
  FechaEnvio        TIMESTAMP    NULL,
  FechaRecepcion    TIMESTAMP    NULL,
  Estado            VARCHAR(20)  NOT NULL,
  Observacion       VARCHAR(300) NULL,
  PRIMARY KEY (IDtraslado)
);

CREATE TABLE Detalle_traslado
(
  IDdetalleTraslado INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDtraslado        INT NOT NULL,
  IDproducto        INT NOT NULL,
  Cantidad          INT NOT NULL,
  PRIMARY KEY (IDdetalleTraslado)
);

CREATE TABLE Movimiento_inventario
(
  IDMovimiento      INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  IDproducto        INT          NOT NULL,
  IDusuario         INT          NOT NULL,
  IDSucursal        INT          NOT NULL,
  IDdetalleCompra   INT          NULL,
  IDdetalleVenta    INT          NULL,
  IDdetalleTraslado INT          NULL,
  TipoMovimiento    VARCHAR(20)  NOT NULL,
  Cantidad          INT          NOT NULL,
  Motivo            VARCHAR(100) NOT NULL,
  Fecha             TIMESTAMP    NOT NULL,
  PRIMARY KEY (IDMovimiento)
);

